import assert from 'node:assert/strict';
const handlers = {};
globalThis.window = { addEventListener(type, handler) { handlers[type] = handler; } };
const { initInput, mouse } = await import('../web/js/input.js');
const { config } = await import('../web/js/config.js');
const { menu, playerSetup, initPlayerSetup, menuTick } = await import('../web/js/menu.js');
initInput({ addEventListener() {} });
config.numPlayers = 2;
initPlayerSetup();
menu.screen = 'player_setup';
menu.playerSetupIdx = 0;
function key(code, value) {
  handlers.keydown({code, key: value, preventDefault() {}});
  const result = menuTick();
  handlers.keyup({code, preventDefault() {}});
  return result;
}
assert.equal(playerSetup[0].name, '');
key('KeyA', 'a');
key('KeyB', 'B');
assert.equal(playerSetup[0].editName, 'aB');
assert.equal(playerSetup[0].name, '', 'typing must not commit the name');
key('Backspace', 'Backspace');
key('Enter', 'Enter');
assert.equal(playerSetup[0].name, 'a');
assert.equal(playerSetup[0].editName, undefined);
assert.equal(menu.playerSetupIdx, 0, 'Enter commits before advancing');
key('KeyN', 'n');
key('KeyZ', 'z');
key('Escape', 'Escape');
assert.equal(playerSetup[0].name, 'a', 'Escape cancels the replacement');
assert.equal(menu.screen, 'player_setup');
key('Space', ' ');
assert.equal(playerSetup[0].aiType, 4, 'first computer choice is Tosser');
key('KeyC', 'c');
assert.equal(playerSetup[0].aiType, 5, 'C selects Chooser');
key('Space', ' ');
assert.equal(playerSetup[0].aiType, 0);
key('Space', ' ');
assert.equal(playerSetup[0].aiType, 5, 'computer selection survives switching back');
mouse.over = true;
mouse.x = 110; mouse.y = 220; mouse.clicked = 1;
menuTick();
assert.equal(playerSetup[0].aiType, 3, 'clicking Poolshark selects its radio option');
mouse.over = false;
key('Space', ' ');
key('KeyD', 'd');
assert.equal(menu.playerSetupIdx, 1, 'Done advances the committed player');
assert.equal(playerSetup[1].name, '');
assert.equal(playerSetup[1].editName, '');
assert.equal(playerSetup[1].aiType, 0, 'the next player starts in human name entry');
console.log('Player setup typing, case, commit, cancel, AI selection and Done transitions pass.');
